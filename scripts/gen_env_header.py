#!/usr/bin/env python3
"""Generate the OpenShock build headers into --out-dir.

``openshock_board.h``: chip identity, build mode and log level. The same for every board of a
build variant; the board itself is stamped into the image after linking (scripts/utils/stamping.py).

``openshock_version.h``: firmware version and git commit, which change every commit. Kept apart
so the version only rebuilds the few translation units that include it.

The version comes from OPENSHOCK_FW_VERSION (required in CI), else a local ``0.0.0-local`` fallback.
"""

import argparse
import os
import re
import subprocess
from pathlib import Path

from utils import boards, github
from utils.files import write_if_changed


def split_semver(version: str):
    pattern = (
        r'^v?(?P<major>\d+)\.(?P<minor>\d+)\.(?P<patch>\d+)'
        r'(?:-(?P<prerelease>[0-9A-Za-z.-]+))?(?:\+(?P<build>[0-9A-Za-z.-]+))?$'
    )
    m = re.match(pattern, version)
    if not m:
        raise ValueError(f'Invalid semver version: {version!r}')
    return (
        int(m.group('major')),
        int(m.group('minor')),
        int(m.group('patch')),
        m.group('prerelease'),
        m.group('build'),
    )


def c_string(value: str) -> str:
    escaped = value.replace('\\', '\\\\').replace('"', '\\"')
    return f'"{escaped}"'


def serialize(value: int | str) -> str:
    """An int is a bare number; anything else a C string, even one that looks numeric (a prerelease of "1")."""
    return str(value) if isinstance(value, int) else c_string(value)


def git_commit() -> str | None:
    commit = os.environ.get('OPENSHOCK_FW_GIT_COMMIT')
    if commit:
        return commit
    try:
        return subprocess.check_output(['git', 'rev-parse', 'HEAD'], text=True, stderr=subprocess.DEVNULL).strip()
    except Exception:
        return None


def resolve_version() -> str:
    version = os.environ.get('OPENSHOCK_FW_VERSION')
    if version:
        return version
    if github.is_ci():
        raise SystemExit('error: OPENSHOCK_FW_VERSION must be set for CI builds')
    commit = git_commit()
    return '0.0.0-local' + (f'+{commit[:7]}' if commit else '')


def render(title: str, defines: dict[str, int | str]) -> str:
    lines = ['// Generated by scripts/gen_env_header.py - do not edit.', f'// {title}', '#pragma once', '']
    lines += [f'#define {key} {serialize(defines[key])}' for key in sorted(defines)]
    return '\n'.join(lines) + '\n'


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--out-dir', required=True, help='directory to write the headers into')
    ap.add_argument('--target', required=True, help='IDF target the build is configured for (IDF_TARGET)')
    ap.add_argument(
        '--version-only',
        action='store_true',
        help='write only openshock_version.h (the per-build refresh; the board header is written at configure)',
    )
    args = ap.parse_args(argv)

    chip = boards.chip_for_target(args.target)
    mode, log_level = github.build_mode()
    board = {
        'OPENSHOCK_FW_CHIP': chip,
        'OPENSHOCK_FW_CHIP_' + chip.upper().replace('-', '').replace('_', ''): 1,
        'OPENSHOCK_FW_MODE': mode,
        'OPENSHOCK_LOG_LEVEL': log_level,
    }

    version = resolve_version()
    major, minor, patch, prerelease, build = split_semver(version)
    version_defines: dict[str, int | str] = {
        'OPENSHOCK_FW_VERSION': version,
        'OPENSHOCK_FW_VERSION_MAJOR': major,
        'OPENSHOCK_FW_VERSION_MINOR': minor,
        'OPENSHOCK_FW_VERSION_PATCH': patch,
    }
    if prerelease is not None:
        version_defines['OPENSHOCK_FW_VERSION_PRERELEASE'] = prerelease
    if build is not None:
        version_defines['OPENSHOCK_FW_VERSION_BUILD'] = build
    commit = git_commit()
    if commit is not None:
        version_defines['OPENSHOCK_FW_GIT_COMMIT'] = commit

    headers = [('openshock_version.h', 'Firmware version and git commit. Changes every commit.', version_defines)]
    if not args.version_only:
        headers.insert(0, ('openshock_board.h', 'Chip identity, build mode and log level.', board))

    out_dir = Path(args.out_dir)
    written = [name for name, title, defines in headers if write_if_changed(out_dir / name, render(title, defines))]
    print(f'gen_env_header: wrote {", ".join(written)} to {out_dir}' if written else f'gen_env_header: {out_dir} already up to date')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
