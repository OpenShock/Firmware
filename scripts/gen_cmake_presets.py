#!/usr/bin/env python3
"""Generate CMakePresets.json: one configure and one build preset per board.

    python scripts/gen_cmake_presets.py            # rewrite CMakePresets.json
    python scripts/gen_cmake_presets.py --check    # exit 1 if it is out of date (tests)

A preset passes only OPENSHOCK_BOARD; the root CMakeLists.txt derives the chip and sdkconfig layers
from boards/<board>.defaults and activates ESP-IDF itself. So `cmake --preset <board>` works from
CLion or any terminal, and `cmake --build --preset <board>` builds it. The file is committed and
regenerated when a board is added; scripts/tests/test_cmake_presets.py keeps it current.

Once a CMakePresets.json exists, idf.py (ESP-IDF 6.1+) always configures with a preset: `default` when
there is one, otherwise the first in the file. So `default` is a real board (DEFAULT_BOARD), and a bare
`idf.py menuconfig` or `idf.py build` configures that board. idf.py reads a preset's binaryDir as is,
without macro expansion or inheritance, so every preset spells out its own generator and a relative
build directory, build/<board>: the one scripts/build.py uses for that board. CMake refuses a hidden
preset, so `default` stays visible. scripts/build.py runs under it too; its -B and -D arguments
(including OPENSHOCK_BOARD) override the preset's binaryDir and cache, so it builds what it asks for.
"""

import argparse
import json
from pathlib import Path

from utils.boards import all_boards
from utils.paths import ROOT

PRESETS_PATH = ROOT / 'CMakePresets.json'
# idf.py selects a configure preset of this name when none is given; keep it visible (not hidden).
DEFAULT_PRESET = 'default'
# The board the `default` preset configures, i.e. what a bare `idf.py menuconfig` or `idf.py build` gets.
DEFAULT_BOARD = 'OpenShock-Core-V2'


def configure_preset(name: str, board: str, display_name: str) -> dict:
    return {
        'name': name,
        'displayName': display_name,
        'generator': 'Ninja',
        'binaryDir': f'build/{board}',  # relative to the source directory; idf.py expands no macros
        'cacheVariables': {'OPENSHOCK_BOARD': board},
    }


def presets() -> dict:
    boards = all_boards()
    if DEFAULT_BOARD not in boards:
        raise SystemExit(f'error: DEFAULT_BOARD {DEFAULT_BOARD!r} has no boards/{DEFAULT_BOARD}.defaults')
    default = configure_preset(
        DEFAULT_PRESET, DEFAULT_BOARD, f'default ({DEFAULT_BOARD}; what idf.py picks when it is given no preset)'
    )
    default['description'] = 'Generated by scripts/gen_cmake_presets.py from boards/*.defaults; do not edit.'
    return {
        'version': 3,
        'cmakeMinimumRequired': {'major': 3, 'minor': 22, 'patch': 0},
        'configurePresets': [default, *(configure_preset(board, board, board) for board in boards)],
        'buildPresets': [{'name': board, 'configurePreset': board} for board in boards],
    }


def render() -> str:
    return json.dumps(presets(), indent=2) + '\n'


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true', help='fail if CMakePresets.json is out of date')
    ap.add_argument('--output', type=Path, default=PRESETS_PATH)
    args = ap.parse_args(argv)

    text = render()
    if args.check:
        current = args.output.read_text(encoding='utf-8') if args.output.is_file() else ''
        if current != text:
            print(f'{args.output} is out of date: run python scripts/gen_cmake_presets.py')
            return 1
        return 0
    args.output.write_text(text, encoding='utf-8', newline='\n')
    print(f'wrote {args.output}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
