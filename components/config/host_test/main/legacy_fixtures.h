#pragma once

// Config files exactly as the Arduino firmware wrote them to the "config" littlefs
// partition, used to check that an upgraded hub keeps its settings.
//
// How these bytes were produced: ../legacy/gen_legacy_config.cpp (host_test/legacy)
// contains the RootConfig / *Config::ToFlatbuffers bodies of the old firmware,
// transcribed verbatim, followed by FinishHubConfigBuffer as in its Config.cpp
// trySaveConfig. It was compiled against the old firmware's own generated schema
// header and the flatbuffers commit that firmware pinned in platformio.ini:
//
//   git show <tag>:include/serialization/_fbs/HubConfig_generated.h    (and WifiAuthMode_generated.h for develop)
//   git -C components/flatbuffers/flatbuffers archive <commit> include
//
//   1.5.2   (latest stable release): flatbuffers 8b02fe6178427b96aea25396b53ea4ae8cadd7d8
//   develop (d9a47e53, same schema as 1.6.0-rc.1): flatbuffers 81edeb17d9118143f2c81caf27edfb0df401279e, built with -DLEGACY_DEVELOP
//
// All three hold the same settings (see test_legacy.cpp for the expected values):
//   rf          txPin 15, keepAlive true (kV152ConfigKeepAliveOff / kDevelopConfig: false)
//   wifi        AP SSID "MyHubAP", hostname "my-hub", credentials
//                 1 "HomeNet" / "hunter22"  (develop: WPA2_PSK, BSSID 12:34:56:78:9a:bc)
//                 2 "Guest"   / ""          (develop: Open)
//                 3 "Office"  / "s3cret!"   (develop: auth mode UNKNOWN)
//   captive     alwaysEnabled true
//   backend     domain "api.example.org", authToken "tok_0123456789abcdef"
//   serialInput echo false
//   otaUpdate   disabled, cdn "fw.example.org", channel Beta, checkOnStartup, checkPeriodically,
//               interval 120, no backend management, manual approval, updateId 4242, step Validating
//   estop       enabled, GPIO13
// 1.5.2's schema has no WiFiCredentials auth_mode / bssid, and declares RFConfig
// keepalive_enabled with default false (develop: true).

